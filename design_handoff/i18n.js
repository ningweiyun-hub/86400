window.translate86400 = function (root, en) {
  if (!root) return;
  const D = window.I18N_86400;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => {
      const p = n.parentNode;
      if (!p || p.nodeName === 'SCRIPT' || p.nodeName === 'STYLE') return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(n => {
    if (en) {
      const key = n.nodeValue.trim();
      if (!key) return;
      const hit = D[key];
      if (hit) {
        if (n.__zh === undefined) n.__zh = n.nodeValue;
        const next = n.nodeValue.replace(key, hit);
        if (n.nodeValue !== next) n.nodeValue = next;
      }
    } else if (n.__zh !== undefined) {
      if (n.nodeValue !== n.__zh) n.nodeValue = n.__zh;
      n.__zh = undefined;
    }
  });
};
